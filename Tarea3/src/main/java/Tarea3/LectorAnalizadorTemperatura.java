    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
        // TODO add your handling code here:
    indice = 0;
   

    try (BufferedReader br = new BufferedReader(new FileReader(ruta))) {
        String linea;
        while ((linea = br.readLine()) != null && indice < temperaturas.length) {
            linea = linea.trim();
            if (!linea.isEmpty()) {
                temperaturas[indice] = Double.parseDouble(linea);
                indice++;
            }
        }
        JOptionPane.showMessageDialog(this, "Los datos fueron cargados");
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al leer el archivo: " + e.getMessage());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El archivo contiene un valor no numérico.");
    }
    }//GEN-LAST:event_btnCargarActionPerformed

    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        // TODO add your handling code here:
    if (indice == 0) {
        JOptionPane.showMessageDialog(this, "Primero debe cargar los datos.");
        return;
    }

    double suma = 0;
    int calidos = 0;
    int frescos = 0;

    for (int i = 0; i < indice; i++) {
        suma += temperaturas[i];
        if (temperaturas[i] >= 25.0) {
            calidos++;
        } else {
            frescos++;
        }
    }

    double promedio = suma / indice;

    taAnalisis.setText(
        "Análisis Climático\n" +
        "------------------\n" +
        "Promedio de Temperatura: " + String.format(Locale.US, "%.1f", promedio) + "\n" +
        "Días Calidos (>= 25°): " + calidos + "\n" +
        "Días Frescos (< 25°): " + frescos
 );
    }//GEN-LAST:event_btnCalcularActionPerformed

