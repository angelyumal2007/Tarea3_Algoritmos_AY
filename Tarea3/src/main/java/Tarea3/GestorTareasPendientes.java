    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
        // TODO add your handling code here:
    if (indice < tareas.length) {
        JOptionPane.showMessageDialog(this, "Faltan tareas: ingresadas " + indice + " de 5.");
        return;
    }

    File carpeta = new File("temp");
    if (!carpeta.exists()) {
        carpeta.mkdirs();
    }
    File archivo = new File(carpeta, "AngelYuman_agenda.txt");

    // 1. Crear en temp
    try (PrintWriter pw = new PrintWriter(new FileWriter(archivo))) {
        pw.println("Agenda de Tareas");
        for (int i = 0; i < tareas.length; i++) {
            pw.println((i + 1) + ". " + tareas[i]);
        }
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al escribir el archivo: " + e.getMessage());
        return;
    }

    // 2. Leer desde temp y mostrar en el área de texto
    StringBuilder contenido = new StringBuilder();
    try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
        String linea;
        while ((linea = br.readLine()) != null) {
            contenido.append(linea).append("\n");
        }
        taMostrarTareas.setText(contenido.toString());
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al leer el archivo: " + e.getMessage());
    }

    }//GEN-LAST:event_btnExportarActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        if (indice >= tareas.length) {
        JOptionPane.showMessageDialog(this, "Ya ingresaste las 5 tareas.");
        return;
    }
 
    String texto = txtTareas.getText().trim();
 
    if (texto.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Escribe la descripción de la tarea.");
        txtTareas.requestFocus();
        return;
    }
 
    tareas[indice] = texto;
    indice++;
 
    taMostrarTareas.append(indice + ". " + texto + "\n");
 
    txtTareas.setText("");
    txtTareas.requestFocus();
    }//GEN-LAST:event_btnAgregarActionPerformed

