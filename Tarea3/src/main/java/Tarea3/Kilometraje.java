    private void btnReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReporteActionPerformed
        // TODO add your handling code here:
    if (indice < recorridos.length) {
        JOptionPane.showMessageDialog(this, "Faltan rutas: ingresadas " + indice + " de 7.");
        return;
    }
    double total = 0;
    for (int i = 0; i < recorridos.length; i++) {
        total += recorridos[i];
    }
    double promedio = total / recorridos.length;


    File archivo = new File("temp", "AngelYuman_reporte_rutas.txt");

    // 1. Crear en temp
    try (PrintWriter pw = new PrintWriter(new FileWriter(archivo))) {
        pw.println("Reporte Semanal de Rutas");
        pw.println("Total de Kilómetros: " + String.format(Locale.US, "%.1f", total));
        pw.println("Promedio Diario: " + String.format(Locale.US, "%.1f", promedio));
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al escribir el archivo: " + e.getMessage());
        return;
    }

    // 2. Leer desde tem
    StringBuilder contenido = new StringBuilder();
    try (BufferedReader br = new BufferedReader(new FileReader(archivo))) {
        String linea;
        while ((linea = br.readLine()) != null) {
            contenido.append(linea).append("\n");
        }
        JOptionPane.showMessageDialog(this, contenido.toString(), "Reporte generado", JOptionPane.INFORMATION_MESSAGE);
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al leer el archivo: " + e.getMessage());
    }
    }//GEN-LAST:event_btnReporteActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
         if (indice >= recorridos.length) {
        JOptionPane.showMessageDialog(this, "Ya ingresó los 7 recorridos. Presione Generar Reporte.");
        return;
    }
    try {
        double km = Double.parseDouble(txtKilometraje.getText().trim().replace(',', '.'));
        if (km < 0) {
            JOptionPane.showMessageDialog(this, "El kilometraje no puede ser negativo.");
            return;
        }
        recorridos[indice] = km;
        indice++;
        txtKilometraje.setText("");
        txtKilometraje.requestFocus();
        JOptionPane.showMessageDialog(this, "Ruta " + indice + " de 7 agregada.");
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Ingrese un valor numérico válido.");
    }
    }//GEN-LAST:event_btnAgregarActionPerformed

